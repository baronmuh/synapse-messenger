"""Strict validation of the envelope, parameters and formats of the API v1.

Applied rules (SPEC.txt specification):

* envelope exactly ``{api_version, command, parameters}`` ;
* any unknown, missing or wrong-typed field -> ``INVALID_ARGUMENT`` ;
* usernames: 3-64 ASCII characters ``[a-z0-9_-]`` after
  lowercase normalization; spaces and other characters are
  refused, never removed;
* passwords: >= 12 printable Unicode code points, never
  normalized;
* content: valid UTF-8, NFC, trimmed of leading/trailing White_Space
  characters, then 1-10,000 code points, without control characters;
* ``client_message_id``: 1-128 ASCII characters ``[A-Za-z0-9._:-]``;
* textual UUIDv4 accepted case-insensitively.
"""

from __future__ import annotations

import json
import re
import unicodedata
import uuid
from datetime import datetime, timedelta, timezone
from typing import Any

from .errors import ApiError, INVALID_ARGUMENT, UNKNOWN_COMMAND

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

API_VERSION = "v2"

USERNAME_RE = re.compile(r"^[A-Za-z0-9_-]+$")
CLIENT_MESSAGE_ID_RE = re.compile(r"^[A-Za-z0-9._:-]+$")
UUID4_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")

MIN_USERNAME_LEN = 3
MAX_USERNAME_LEN = 64
MIN_PASSWORD_LEN = 12
MIN_CONTENT_LEN = 1
MAX_CONTENT_LEN = 10_000
MIN_DESCRIPTION_LEN = 1
MAX_DESCRIPTION_LEN = 500
MIN_CLIENT_MESSAGE_ID_LEN = 1
MAX_CLIENT_MESSAGE_ID_LEN = 128
MIN_BUSINESS_REFERENCE_LEN = 1
MAX_BUSINESS_REFERENCE_LEN = 128
MIN_LIMIT = 1
MAX_LIMIT = 100
DEFAULT_LIMIT = 50

# Unicode categories allowed in a password: letters, marks,
# numbers, punctuation, symbols and space separators (spaces are
# explicitly allowed). Everything else (control, format, surrogates,
# line/paragraph separators...) is refused. ``unicodedata.category``
# returns two letters (e.g. "Ll"): we compare the major one, except
# for "Zs" (space) which is the only allowed "Z" category.
_PASSWORD_ALLOWED_MAJOR = frozenset("LMNPS")

# ---------------------------------------------------------------------------
# UTC service time
# ---------------------------------------------------------------------------


def now_utc() -> str:
    """Exact UTC timestamp in ``YYYY-MM-DDTHH:mm:ss.sssZ`` format.

    Generated by the service (never by the calling agent), with
    millisecond precision, conforming to the specification.
    """
    dt = datetime.now(timezone.utc)
    ms = dt.microsecond // 1000
    return f"{dt.strftime('%Y-%m-%dT%H:%M:%S')}.{ms:03d}Z"


def now_utc_offset(seconds: float) -> str:
    """UTC timestamp shifted by ``-seconds`` (same format as ``now_utc``).

    The fixed ``YYYY-MM-DDTHH:mm:ss.sssZ`` format makes comparisons of
    strings equivalent for chronological comparisons.
    """
    dt = datetime.now(timezone.utc) - timedelta(seconds=seconds)
    ms = dt.microsecond // 1000
    return f"{dt.strftime('%Y-%m-%dT%H:%M:%S')}.{ms:03d}Z"


def _invalid(message: str) -> ApiError:
    return ApiError(INVALID_ARGUMENT, message)


# ---------------------------------------------------------------------------
# Usernames
# ---------------------------------------------------------------------------


def normalize_username(raw: Any) -> str:
    """Validates and normalizes a username.

    Accepts ``[A-Za-z0-9_-]``, 3 to 64 characters, normalized to lowercase.
    """
    if not isinstance(raw, str):
        raise _invalid("The username must be a string")
    if not (MIN_USERNAME_LEN <= len(raw) <= MAX_USERNAME_LEN):
        raise _invalid(
            f"The username must contain between {MIN_USERNAME_LEN} and "
            f"{MAX_USERNAME_LEN} characters"
        )
    if not USERNAME_RE.fullmatch(raw):
        raise _invalid(
            "The username may only contain ASCII letters, "
            "digits, '_' and '-' (spaces are refused)"
        )
    return raw.lower()


def is_valid_username(raw: str) -> bool:
    """Checks without raising (used by filters)."""
    try:
        normalize_username(raw)
        return True
    except ApiError:
        return False


def normalize_organization_name(raw: Any) -> str:
    """Normalizes an organization name (same rules as usernames).

    Organization names and usernames share the same character
    set but form two distinct namespaces (section 3.5).
    """
    if not isinstance(raw, str):
        raise _invalid("The organization name must be a string")
    if not (MIN_USERNAME_LEN <= len(raw) <= MAX_USERNAME_LEN):
        raise _invalid(
            f"The organization name must contain between {MIN_USERNAME_LEN} and "
            f"{MAX_USERNAME_LEN} characters"
        )
    if not USERNAME_RE.fullmatch(raw):
        raise _invalid(
            "The organization name may only contain ASCII letters, "
            "digits, '_' and '-' (spaces are refused)"
        )
    return raw.lower()


