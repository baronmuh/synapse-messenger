def validate_envelope(request: Any) -> tuple[str, dict]:
    """Validates the complete envelope of a request.

    Returns ``(command, validated_parameters)``. Raises ``ApiError`` with
    ``UNKNOWN_COMMAND`` for an unknown command or ``INVALID_ARGUMENT``
    for any other format problem.

    The validated parameters contain the transformed values (normalized
    names, lowercase UUIDs, NFC/trimmed content, resolved limit).
    """
    if not isinstance(request, dict):
        raise _invalid("The request must be a JSON object")
    _ensure_exact_keys(request, ("api_version", "command", "parameters"), "envelope")

    api_version = request["api_version"]
    if not isinstance(api_version, str) or api_version != API_VERSION:
        raise _invalid(f"api_version must be '{API_VERSION}'")

    command = request["command"]
    if not isinstance(command, str):
        raise _invalid("command must be a string")
    if command not in COMMAND_SPECS:
        raise ApiError(UNKNOWN_COMMAND, f"Unknown command: {command}")

    parameters = request["parameters"]
    if not isinstance(parameters, dict):
        raise _invalid("parameters must be a JSON object")

    spec = COMMAND_SPECS[command]
    allowed = {param[0] for param in spec[1]}
    _ensure_exact_keys(parameters, tuple(sorted(allowed)), "parameters")

    validated: dict = {}
    for name, type_, required, validator in spec[1]:
        raw = parameters[name]
        if raw is None:
            if required:
                raise _invalid(f"The parameter '{name}' is required")
            # Validators of optional parameters accept None:
            # they apply the default value (e.g. limit -> 50) or
            # return None (status, sender_username, conversation_id...).
            if validator is not None:
                raw = validator(raw)
            validated[name] = raw
            continue
        if type(raw) is not type_:
            raise _invalid(f"The parameter '{name}' must be of type {type_.__name__}")
        if validator is not None:
            raw = validator(raw)
        validated[name] = raw
    return command, validated


def _ensure_exact_keys(mapping: dict, allowed: tuple[str, ...], label: str) -> None:
    """Refuses any unknown or missing field (exact keys)."""
    actual = set(mapping.keys())
    expected = set(allowed)
    unknown = actual - expected
    if unknown:
        raise _invalid(f"Unknown field in {label} : {sorted(unknown)[0]}")
    missing = expected - actual
    if missing:
        raise _invalid(f"Missing field in {label} : {sorted(missing)[0]}")


def parse_json_request(data: bytes) -> Any:
    """Strictly decodes a JSON request (strict UTF-8, no duplicate keys)."""
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise _invalid("Invalid JSON request (UTF-8)") from exc
    try:
        return json.loads(text, object_pairs_hook=_reject_duplicate_keys)
    except json.JSONDecodeError as exc:
        raise _invalid("Invalid JSON request") from exc
    except ValueError as exc:
        # duplicate keys (ValueError raised by object_pairs_hook)
        raise _invalid("Invalid JSON request") from exc
    except RecursionError as exc:
        # deeply nested JSON: malformed request, not an internal error
        raise _invalid("Invalid JSON request (excessive nesting)") from exc


def _reject_duplicate_keys(pairs: list) -> dict:
    result: dict = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate key: {key}")
        result[key] = value
    return result
