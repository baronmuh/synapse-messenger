def validate_client_message_id(raw: Any) -> str:
    """Validates a ``client_message_id``: 1-128 characters ``[A-Za-z0-9._:-]``."""
    if not isinstance(raw, str):
        raise _invalid("client_message_id must be a string")
    if not (MIN_CLIENT_MESSAGE_ID_LEN <= len(raw) <= MAX_CLIENT_MESSAGE_ID_LEN):
        raise _invalid(
            f"client_message_id must contain between {MIN_CLIENT_MESSAGE_ID_LEN} and "
            f"{MAX_CLIENT_MESSAGE_ID_LEN} characters"
        )
    if not CLIENT_MESSAGE_ID_RE.fullmatch(raw):
        raise _invalid(
            "client_message_id may only contain ASCII characters "
            "from a-z, A-Z, 0-9, '.', '_', ':' and '-'"
        )
    return raw


def normalize_uuid(raw: Any, field: str = "identifier") -> str:
    """Validates a textual UUIDv4 (case-insensitive), returns the lowercase form."""
    if not isinstance(raw, str):
        raise _invalid(f"{field} must be a string")
    if not UUID4_RE.fullmatch(raw):
        raise _invalid(f"{field} must be a valid UUIDv4")
    value = uuid.UUID(raw)
    if value.version != 4 or value.variant != uuid.RFC_4122:
        raise _invalid(f"{field} must be a valid UUIDv4")
    return str(value)


def normalize_business_reference(raw: Any) -> str | None:
    """Normalizes a business reference: NFC string of 1-128 code points,
    no control characters, opaque to the server.

    ``None`` (optional parameter not provided) is accepted: a message
    without a business reference stays valid.
    """
    if raw is None:
        return None
    if not isinstance(raw, str):
        raise _invalid("business_reference must be a string")
    _reject_surrogates(raw)
    ref = unicodedata.normalize("NFC", raw)
    ref = ref.strip()
    length = len(ref)
    if not (MIN_BUSINESS_REFERENCE_LEN <= length <= MAX_BUSINESS_REFERENCE_LEN):
        raise _invalid(
            f"business_reference must contain between {MIN_BUSINESS_REFERENCE_LEN} and "
            f"{MAX_BUSINESS_REFERENCE_LEN} Unicode code points after normalization"
        )
    for ch in ref:
        if unicodedata.category(ch) == "Cc":
            raise _invalid("business_reference cannot contain control characters")
    return ref


