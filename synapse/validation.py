#: Reserved suffix of human accounts (username derived from the organization).
HUMAN_SUFFIX = "_humain"


def human_username_for(organization_name: str) -> str:
    """Username derived from the human account of an organization.

    Normal form: ``{organization_name}_humain`` (unique because
    organization names are unique). If the derived name would exceed the
    username limit (very long organization names, historical case), a
    truncated form + short deterministic fingerprint — always unique and stable.
    """
    derived = f"{organization_name}{HUMAN_SUFFIX}"
    if len(derived) <= MAX_USERNAME_LEN:
        return derived
    import hashlib

    digest = hashlib.sha256(organization_name.encode("utf-8")).hexdigest()[:8]
    prefix_len = MAX_USERNAME_LEN - len(HUMAN_SUFFIX) - 1 - len(digest)
    return f"{organization_name[:prefix_len]}{HUMAN_SUFFIX}_{digest}"


def is_reserved_human_username(username: str) -> bool:
    """A name containing the human marker is reserved for the system.

    Covers the normal form (``*_humain``) and the long derived form
    (``*_humain_<8 hex>``). ``create_agent`` refuses it: no collision
    possible with a self-created human account.
    """
    return username.endswith(HUMAN_SUFFIX) or f"{HUMAN_SUFFIX}_" in username


def validate_bool(raw: Any) -> bool:
    """Validates a strict JSON boolean (``true`` or ``false``).

    ``None`` (optional parameter not used) returns ``False``:
    permissions and policies are opt-in (least privilege principle).
    """
    if raw is None:
        return False
    if type(raw) is not bool:
        raise _invalid("The parameter must be a JSON boolean (true or false)")
    return raw


# ---------------------------------------------------------------------------
# Passwords
# ---------------------------------------------------------------------------


def validate_password(raw: Any) -> str:
    """Validates a password: >= 12 printable Unicode characters.

    The password is never normalized: it is used exactly as
    provided.
    """
    if not isinstance(raw, str):
        raise _invalid("The password must be a string")
    if len(raw) < MIN_PASSWORD_LEN:
        raise _invalid(f"The password must contain at least {MIN_PASSWORD_LEN} characters")
    for ch in raw:
        cat = unicodedata.category(ch)
        if not (cat[0] in _PASSWORD_ALLOWED_MAJOR or cat == "Zs"):
            raise _invalid(
                "The password may only contain printable Unicode "
                "characters (control characters, line breaks and "
                "null characters are forbidden)"
            )
    return raw


# ---------------------------------------------------------------------------
# Message content
# ---------------------------------------------------------------------------


def normalize_content(raw: Any) -> str:
    """Normalizes the content of a message.

    Steps (in specification order):
    1. valid UTF-8 string (guaranteed by JSON decoding, surrogates refused);
    2. Unicode NFC normalization ;
    3. removal of leading/trailing White_Space characters;
    4. final check: 1 to 10,000 code points, no control characters.
    """
    if not isinstance(raw, str):
        raise _invalid("The message must be a string")
    _reject_surrogates(raw)
    content = unicodedata.normalize("NFC", raw)
    content = content.strip()
    length = len(content)
    if not (MIN_CONTENT_LEN <= length <= MAX_CONTENT_LEN):
        raise _invalid(
            f"The content must contain between {MIN_CONTENT_LEN} and {MAX_CONTENT_LEN} "
            "Unicode code points after normalization"
        )
    for ch in content:
        if unicodedata.category(ch) == "Cc":
            raise _invalid("The content cannot contain control characters")
    return content


def _reject_surrogates(value: str) -> None:
    """Rejects lone surrogates (not encodable in UTF-8)."""
    for ch in value:
        code = ord(ch)
        if 0xD800 <= code <= 0xDFFF:
            raise _invalid("The text contains invalid UTF-8 sequences")


def normalize_description(raw: Any) -> str:
    """Normalizes an agent description (section 3 of the specification).

    Same rules as message content, with a limit of 500 code
    points: valid UTF-8 string, NFC normalization, trimming of
    leading/trailing `White_Space` characters, 1 to 500 code points, no
    control characters.
    """
    if not isinstance(raw, str):
        raise _invalid("The description must be a string")
    _reject_surrogates(raw)
    description = unicodedata.normalize("NFC", raw)
    description = description.strip()
    length = len(description)
    if not (MIN_DESCRIPTION_LEN <= length <= MAX_DESCRIPTION_LEN):
        raise _invalid(
            f"The description must contain between {MIN_DESCRIPTION_LEN} and "
            f"{MAX_DESCRIPTION_LEN} Unicode code points after normalization"
        )
    for ch in description:
        if unicodedata.category(ch) == "Cc":
            raise _invalid("The description cannot contain control characters")
    return description


