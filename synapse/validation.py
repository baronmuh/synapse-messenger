# Agent cards (F2) and capability search (F3)
# ---------------------------------------------------------------------------

MIN_CAPABILITIES = 1
MAX_CAPABILITIES = 50
MIN_CAPABILITY_LEN = 1
MAX_CAPABILITY_LEN = 64
MAX_CARD_TEXT_LEN = 128
MAX_CARD_LIMITS_LEN = 256


def _normalize_card_text(raw: Any, field: str, max_len: int) -> str | None:
    """Normalizes an optional card text field: NFC, bounds, no
    control characters. ``None`` if absent."""
    if raw is None:
        return None
    if not isinstance(raw, str):
        raise _invalid(f"{field} must be a string")
    _reject_surrogates(raw)
    text = unicodedata.normalize("NFC", raw).strip()
    if not (1 <= len(text) <= max_len):
        raise _invalid(
            f"{field} must contain between 1 and {max_len} Unicode code points after "
            "normalization"
        )
    for ch in text:
        if unicodedata.category(ch) == "Cc":
            raise _invalid(f"{field} cannot contain control characters")
    return text


def normalize_capabilities(raw: Any) -> list[str] | None:
    """Normalizes a capability list: 1-50 NFC strings of 1-64, deduplicated
    case-insensitively (the first occurrence is kept).

    ``None`` is refused: ``set_agent_card`` requires at least one capability
    (a card without capability makes no sense for discovery).
    """
    if raw is None:
        raise _invalid("capabilities is required")
    if not isinstance(raw, list) or any(isinstance(i, bool) for i in raw):
        raise _invalid("capabilities must be a list of strings")
    if not (MIN_CAPABILITIES <= len(raw) <= MAX_CAPABILITIES):
        raise _invalid(
            f"capabilities must contain between {MIN_CAPABILITIES} and {MAX_CAPABILITIES} "
            "elements"
        )
    out: list[str] = []
    seen: set[str] = set()
    for item in raw:
        value = _normalize_card_text(item, "capability", MAX_CAPABILITY_LEN)
        assert value is not None
        folded = value.casefold()
        if folded not in seen:
            seen.add(folded)
            out.append(value)
    return out


def normalize_tools(raw: Any) -> list[str] | None:
    """Normalizes a tool list: 0-50 NFC strings of 1-64, deduplicated
    case-insensitively (the first occurrence is kept)."""
    if raw is None:
        return []
    if not isinstance(raw, list) or any(isinstance(i, bool) for i in raw):
        raise _invalid("tools must be a list of strings")
    if len(raw) > MAX_CAPABILITIES:
        raise _invalid(f"tools must contain at most {MAX_CAPABILITIES} elements")
    out: list[str] = []
    seen: set[str] = set()
    for item in raw:
        value = _normalize_card_text(item, "tool", MAX_CAPABILITY_LEN)
        assert value is not None
        folded = value.casefold()
        if folded not in seen:
            seen.add(folded)
            out.append(value)
    return out


def _validate_capability_filter(value: Any) -> str | None:
    if value is None:
        return None
    return _normalize_card_text(value, "capability", MAX_CAPABILITY_LEN)


def _validate_card_text_filter(value: Any, field: str) -> str | None:
    if value is None:
        return None
    return _normalize_card_text(value, field, MAX_CARD_TEXT_LEN)


