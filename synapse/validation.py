# Command declaration: ``params`` lists the allowed fields in
# order (name, type, required, optional semantic validator).
# ``org`` indicates that the command requires the authentication of an
# organization (instead of an agent's).
CommandSpec = tuple[str, tuple, bool]  # (name, params, org) -- see build_spec

_P = str  # base JSON type


def _spec(name: str, params: tuple, org: bool = False) -> CommandSpec:
    return (name, params, org)


def _validate_status(value: Any) -> str | None:
    if value is None:
        return None
    if value not in ("read", "unread"):
        raise _invalid("status must be 'read' or 'unread'")
    return value


def _validate_sender_filter(value: Any) -> str | None:
    if value is None:
        return None
    return normalize_username(value)


def _validate_uuid_filter(value: Any) -> str | None:
    if value is None:
        return None
    return normalize_uuid(value, "conversation_id")


def _validate_limit(value: Any) -> int:
    if value is None:
        return DEFAULT_LIMIT
    if isinstance(value, bool) or not isinstance(value, int):
        raise _invalid("limit must be an integer")
    if not (MIN_LIMIT <= value <= MAX_LIMIT):
        raise _invalid(f"limit must be an integer between {MIN_LIMIT} and {MAX_LIMIT}")
    return value


def _validate_command_name(value: Any) -> str | None:
    """Validates ``command_name`` (help): exact name of a command of the API v1.

    Exact comparison, without normalization (specification, section 13): an
    unknown name raises ``UNKNOWN_COMMAND``.
    """
    if value is None:
        return None
    if value not in COMMAND_SPECS:
        raise ApiError(UNKNOWN_COMMAND, f"Unknown command: {value}")
    return value


